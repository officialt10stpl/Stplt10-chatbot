app.post('/api/chat', async (req, res) => {
  try {
    const { message, mobileNumber } = req.body;
    const userMsg = message ? message.trim() : "";
    const lowerMsg = userMsg.toLowerCase();

    // 0. सुरक्षा और प्राइवेसी फिल्टर
    if (lowerMsg.includes("आधार") || lowerMsg.includes("aadhaar") || lowerMsg.includes("adhar") || lowerMsg.includes("rrn") || lowerMsg.includes("mynumber")) {
      return res.json({ 
        reply: "भाई, अपनी संवेदनशील आईडी चैट में कभी भी सीधे टाइप मत करो! अपनी जानकारी पूरी तरह सुरक्षित रखो।" 
      });
    }

    // 1. ऑटो-ग्रीटिंग
    if ((lowerMsg === "hello" || lowerMsg === "hi") && mobileNumber) {
      const playerQuery = await db.collection('players').where('mobile', '==', mobileNumber).get();
      if (!playerQuery.empty) {
        const playerData = playerQuery.docs[0].data();
        return res.json({ 
          reply: `अरे ${playerData.name} भाई! स्वागत है STPL T10 में! 🔥 आपकी Reg ID ${playerData.generatedId} है। बताइए, क्या मदद करूँ?` 
        });
      }
    }

    // 2. पासवर्ड रिकवरी
    if (lowerMsg.includes("पासवर्ड") || lowerMsg.includes("password")) {
      return res.json({ 
        reply: "पासवर्ड के दो रास्ते हैं:\n1. अपनी सही डिटेल मुझे यहीं बताकर पासवर्ड ले लो।\n2. वेबसाइट के WhatsApp नंबर पर एडमिन से संपर्क कर लो।" 
      });
    }

    // 3. रेफरल स्टेटस चेक
    if (lowerMsg.includes("रेफरल") || lowerMsg.includes("referral") || lowerMsg.includes("cashback") || lowerMsg.includes("कैशबैक")) {
      if (!mobileNumber) {
        return res.json({ reply: "भाई, अपना रजिस्टर्ड मोबाइल नंबर या Reg ID बताओ, तभी तो चेक करके बता पाऊंगा!" });
      }
      const playerRef = await db.collection('players').where('mobile', '==', mobileNumber).get();
      if (!playerRef.empty) {
        const pData = playerRef.docs[0].data();
        return res.json({ reply: `भाई, आपके कुल सफल रेफरल ${pData.referralCount || 0} हैं। टारगेट पूरा होते ही कैशबैक मिल जाएगा!` });
      } else {
        return res.json({ reply: "भाई, इस नंबर से कोई रजिस्ट्रेशन नहीं मिला। सही नंबर या Reg ID बताओ।" });
      }
    }

    // 4. ट्रायल सिटीज फेच करना
    if (lowerMsg.includes("शहर") || lowerMsg.includes("city") || lowerMsg.includes("trial") || lowerMsg.includes("kahan")) {
      const citiesSnapshot = await db.collection('trial_cities').get();
      let citiesList = [];
      citiesSnapshot.forEach(doc => citiesList.push(doc.data().cityName));

      if (citiesList.length > 0) {
        return res.json({ reply: `ट्रायल्स 50+ शहरों में हैं। मुख्य शहर: ${citiesList.join(', ')}. अपना शहर लिखकर कन्फर्म करें!` });
      }
    }

    // 5. FAQ स्टैटिक मैचिंग
    for (let key in staticFAQs) {
      if (lowerMsg.includes(key.toLowerCase())) {
        return res.json({ reply: staticFAQs[key] });
      }
    }

    // 6. स्मार्ट फॉलबैक (Gemini API)
    try {
      const geminiPrompt = `
      तुम STPL T10 क्रिकेट लीग के आधिकारिक AI सहायक हो। 
      नियम:
      1. यूजर के सवाल का जवाब बिल्कुल छोटे, सटीक और हिंग्लिश/हिंदी के दोस्ताना अंदाज ("भाई" वाले टोन में) दो।
      2. कभी भी रोबोट की तरह लंबे पैराग्राफ मत लिखो।
      3. किसी भी शहर या ओवरऑल रजिस्ट्रेशन के कुल आंकड़े (Exact Counts) सार्वजनिक रूप से मत बताओ।
      4. ट्रायल्स August 2026 से शुरू होंगे, बैट्समैन का चैलेंज 1 ओवर में 16 रन और बॉलर का 14 रन डिफेंड करना है। फीस ₹999 है।
      
      यूजर का सवाल: "${userMsg}"
      `;

      const response = await ai.models.generateContent({
        model: 'gemini-1.5-flash',
        contents: geminiPrompt,
      });

      const aiReply = response.text ? response.text.trim() : "अरे भाई, बढ़िया सवाल है! इसकी अधिक जानकारी के लिए वेबसाइट के होमपेज पर विजिट करें या WhatsApp सपोर्ट से जुड़ें।";
      return res.json({ reply: aiReply });

    } catch (aiError) {
      console.error("Gemini API Error:", aiError);
      return res.json({ 
        reply: `अरे भाई, आपका सवाल मिल गया है! ${userMsg} के बारे में पूरी डिटेल आपको जल्द ही वेबसाइट पर अपडेट मिलेगी।` 
      });
    }

  } catch (error) {
    console.error(error);
    res.status(500).json({ error: "कुछ गड़बड़ हो गई भाई, दोबारा ट्राई करो!" });
  }
});

